/**
 * Integration Test - Pricing Engine REST API
 *
 * Tests the POST /api/v1/pricing/calculate endpoint end-to-end
 * using the wired-up dependencies (mock infrastructure).
 * Verifies that a valid HTTP 200 response is returned with a calculated amount.
 *
 * Architecture: Clean Architecture - Test Layer
 * Status: LOCKED | Created v2
 */

const assert = require('assert');
const http = require('http');

const PORT = 3099; // Dedicated test port to avoid conflicts
let server;

/**
 * Start the server on a test port before running tests
 */
async function startServer() {
  const app = require('../../run-server');
  return new Promise((resolve) => {
    server = app.listen(PORT, () => {
      console.log(`[TestServer] Listening on http://localhost:${PORT}`);
      resolve();
    });
  });
}

/**
 * Stop the server after tests complete
 */
async function stopServer() {
  return new Promise((resolve) => {
    if (server) {
      server.close(() => {
        console.log('[TestServer] Closed');
        resolve();
      });
    } else {
      resolve();
    }
  });
}

/**
 * Make an HTTP POST request to the calculate endpoint
 */
function postCalculate(payload) {
  return new Promise((resolve, reject) => {
    const data = JSON.stringify(payload);
    const options = {
      hostname: 'localhost',
      port: PORT,
      path: '/api/v1/pricing/calculate',
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Content-Length': Buffer.byteLength(data),
      },
    };

    const req = http.request(options, (res) => {
      let body = '';
      res.on('data', (chunk) => { body += chunk; });
      res.on('end', () => {
        try {
          resolve({
            statusCode: res.statusCode,
            headers: res.headers,
            body: JSON.parse(body),
          });
        } catch {
          resolve({ statusCode: res.statusCode, headers: res.headers, body });
        }
      });
    });

    req.on('error', (err) => reject(err));
    req.write(data);
    req.end();
  });
}

/**
 * Make an HTTP GET request to the health endpoint
 */
function getHealth() {
  return new Promise((resolve, reject) => {
    const options = {
      hostname: 'localhost',
      port: PORT,
      path: '/health',
      method: 'GET',
    };

    const req = http.request(options, (res) => {
      let body = '';
      res.on('data', (chunk) => { body += chunk; });
      res.on('end', () => {
        try {
          resolve({ statusCode: res.statusCode, body: JSON.parse(body) });
        } catch {
          resolve({ statusCode: res.statusCode, body });
        }
      });
    });

    req.on('error', (err) => reject(err));
    req.end();
  });
}

// ── Tests ─────────────────────────────────────────────────────────
async function run() {
  let passed = 0;
  let failed = 0;

  function test(name, fn) {
    try {
      fn();
      passed++;
      console.log('  ✓', name);
    } catch (error) {
      failed++;
      console.log('  ✘', name, ':', error.message);
    }
  }

  async function testAsync(name, fn) {
    try {
      await fn();
      passed++;
      console.log('  ✓', name);
    } catch (error) {
      failed++;
      console.log('  ✘', name, ':', error.message);
    }
  }

  console.log('\n=== PRICING INTEGRATION TESTS ===\n');

  // ── Setup ──────────────────────────────────────────────────────
  await startServer();

  // ── 1. Health check ────────────────────────────────────────────
  await testAsync('GET /health returns 200', async () => {
    const res = await getHealth();
    assert.strictEqual(res.statusCode, 200);
    assert.strictEqual(res.body.module, 'pricing-engine');
    assert.strictEqual(res.body.success, true);
  });

  // ── 2. POST /api/v1/pricing/calculate with distance & duration ─
  await testAsync('POST /api/v1/pricing/calculate returns 200 with totalPrice', async () => {
    const res = await postCalculate({
      distanceKm: 10,
      durationMin: 15,
      serviceType: 'urban_taxi',
    });

    assert.strictEqual(res.statusCode, 200);
    assert.strictEqual(res.body.success, true);
    assert.ok(res.body.data, 'Response must include data');
    assert.ok(typeof res.body.data.totalPrice === 'number', 'totalPrice must be a number');
    assert.ok(res.body.data.totalPrice > 0, 'totalPrice must be greater than 0');
    assert.strictEqual(res.body.data.currencyId, 'IRT');
    // quoteId may be null (generated by downstream persistence), still verify the key exists
    assert.ok('quoteId' in res.body.data, 'Response must include quoteId key');
  });

  // ── 3. POST /api/v1/pricing/calculate with demand factor ──────
  await testAsync('POST /api/v1/pricing/calculate with demandFactor returns higher price', async () => {
    const res = await postCalculate({
      distanceKm: 10,
      durationMin: 15,
      serviceType: 'urban_taxi',
      demandFactor: 2.0,
    });

    assert.strictEqual(res.statusCode, 200);
    assert.strictEqual(res.body.success, true);
    assert.ok(res.body.data.totalPrice > 0, 'totalPrice must be positive');
  });

  // ── 4. POST /api/v1/pricing/calculate with missing params ─────
  await testAsync('POST /api/v1/pricing/calculate returns 400 for missing params', async () => {
    const res = await postCalculate({});

    assert.strictEqual(res.statusCode, 400);
    assert.strictEqual(res.body.success, false);
  });

  // ── 5. Calculate base price: 15000 baseFare + (5000 * 5km) + (1000 * 10min) = 45000
  await testAsync('POST /api/v1/pricing/calculate returns correct calculated amount', async () => {
    const res = await postCalculate({
      distanceKm: 5,
      durationMin: 10,
      serviceType: 'urban_taxi',
    });

    assert.strictEqual(res.statusCode, 200);
    // baseFare(15000) + perKmRate(5000)*5 + perMinuteRate(1000)*10 = 15000 + 25000 + 10000 = 50000
    assert.strictEqual(res.body.data.totalPrice, 50000);
  });

  // ── Teardown ───────────────────────────────────────────────────
  await stopServer();

  // ── Report ─────────────────────────────────────────────────────
  const total = passed + failed;
  console.log(`\n========================================`);
  console.log(`  PRICING INTEGRATION TEST RESULTS: ${passed}/${total} passed`);
  console.log(`  Failed: ${failed}`);
  console.log(`========================================\n`);

  process.exit(failed > 0 ? 1 : 0);
}

run().catch((error) => {
  console.error('✗ Integration test suite failed to run');
  console.error(error.stack || error.message);
  stopServer().then(() => process.exit(1));
});